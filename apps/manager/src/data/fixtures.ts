const makeSettlementEntertainers = (
  batchId: string,
  count: number,
  total: number,
  exceptionCount: number,
) => {
  const branchIds = ['queen', 'empire', 'platinum', 'gobi'] as const
  const ranks = ['Rank 1', 'Rank 2', 'Rank 3'] as const
  const totalCents = Math.round(total * 100)
  const baseCents = Math.floor(totalCents / count)
  const remainder = totalCents % count

  return Array.from({ length: count }, (_, index) => ({
    id: `${batchId}-ent-${String(index + 1).padStart(3, '0')}`,
    name: `Демо ажилтан ${String(index + 1).padStart(2, '0')}`,
    rank: ranks[index % ranks.length],
    branchId: branchIds[index % branchIds.length],
    net: (baseCents + (index < remainder ? 1 : 0)) / 100,
    exceptions: index < exceptionCount ? 1 : 0,
  }))
}

