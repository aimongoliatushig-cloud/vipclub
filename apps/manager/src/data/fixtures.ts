interface SettingOptions {
  valueType?: BranchSetting['valueType']
  unit?: string
  managerEditable?: boolean
  ceoEditable?: boolean
  requiresCeoApproval?: boolean
  highImpact?: boolean
  status?: BranchSetting['status']
  origin?: BranchSetting['origin']
  lockedReason?: string
  sourceDocs: string[]
}

const makeBranchSetting = (
  branch: Branch,
  key: string,
  category: BranchSettingCategory,
  label: string,
  description: string,
  value: string,
  options: SettingOptions,
): BranchSetting => {
  const actor = options.managerEditable === false ? 'Баттүшиг' : branch.manager
  const role = options.managerEditable === false ? 'CEO' : 'Branch Manager'
  return {
    id: `${branch.id}-${key.replaceAll('.', '-')}`,
    key,
    branchId: branch.id,
    category,
    label,
    description,
    value,
    unit: options.unit,
    valueType: options.valueType ?? 'text',
    origin: options.origin ?? 'branch',
    status: options.status ?? 'active',
    managerEditable: options.managerEditable ?? true,
    ceoEditable: options.ceoEditable ?? true,
    requiresCeoApproval: options.requiresCeoApproval ?? false,
    highImpact: options.highImpact ?? false,
    effectiveFrom: '2026-08-01',
    version: 1,
    updatedBy: actor,
    updatedAt: now,
    lockedReason: options.lockedReason,
    sourceDocs: options.sourceDocs,
    history: [{
      id: `history-${branch.id}-${key.replaceAll('.', '-')}-1`,
      actor,
      role,
      action: 'created',
      before: '—',
      after: value,
      reason: options.status === 'configuration-required' ? 'Батлагдсан утга хүлээгдэж байна.' : 'Салбарын анхны тохиргоо.',
      effectiveFrom: '2026-08-01',
      version: 1,
      createdAt: now,
    }],
  }
}

